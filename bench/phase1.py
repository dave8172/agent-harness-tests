"""Phase 1: voice probes through every harness, on Claude Haiku 5.5 and gpt-5.4-nano.

    python bench/phase1.py --runs 10            # estimate, run, score
    python bench/phase1.py --runs 1 --out results/phase1-smoke
    python bench/phase1.py --score-only         # rescore saved replies

Writes <out>/jobs.jsonl, replies.jsonl (resumable), summary.md, replies.md.
"""

import argparse
import collections
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "bench"))
from probes import PROBES  # noqa: E402
from scoring import outcome  # noqa: E402

PRICES = {"anthropic": (0.10, 0.50), "openai": (0.20, 1.25), "ollama": (0, 0)}  # $ per 1M tokens in / out
HARNESSES = [("handrolled", None), ("pydantic", None), ("pi", "sysprompt")]
EXTRA = {("pi", "steer"): {"mid-change", "who-said"}}  # pi's other way to say a mid-conversation instruction
LABEL = {("handrolled", None): "hand-rolled", ("pydantic", None): "Pydantic AI",
         ("pi", "sysprompt"): "pi (system prompt)", ("pi", "steer"): "pi (steer)"}
MODEL = {"anthropic": "Claude Haiku 5.5", "openai": "gpt-5.4-nano", "ollama": "local (Ollama)"}


def build_jobs(runs, only, providers=("anthropic", "openai")):
    jobs = []
    for provider in providers:
        combos = HARNESSES + list(EXTRA)
        for harness, variant in combos:
            for pname, probe in PROBES.items():
                if only and pname not in only:
                    continue
                if (harness, variant) in EXTRA and pname not in EXTRA[(harness, variant)]:
                    continue
                for arm, conv in probe["arms"].items():
                    for i in range(runs):
                        jobs.append({"id": f"{pname}|{arm}|{harness}|{variant}|{provider}|{i}",
                                     "probe": pname, "arm": arm, "harness": harness, "variant": variant,
                                     "provider": provider, "conversation": conv})
    return jobs


def estimate(jobs):
    # ~1,200 input tokens and ~250 output tokens per job (some jobs make a second request)
    cost = collections.Counter()
    for j in jobs:
        pin, pout = PRICES[j["provider"]]
        cost[j["provider"]] += (1500 * pin + 300 * pout) / 1e6
    return cost


def run(out, jobs_path, conc):
    replies = out / "replies.jsonl"
    py = subprocess.Popen([sys.executable, str(ROOT / "bench/run_py.py"), str(jobs_path),
                           str(replies), "--concurrency", str(conc)])
    py.wait()
    subprocess.run(["node", str(ROOT / "bench/run_pi.mjs"), str(jobs_path), str(replies),
                    "--concurrency", str(conc)], check=True)


def score(out):
    jobs = {json.loads(l)["id"]: json.loads(l) for l in open(out / "jobs.jsonl")}
    replies = {}
    for l in open(out / "replies.jsonl"):
        r = json.loads(l)
        if r["error"] is None or r["id"] not in replies:
            replies[r["id"]] = r
    table = collections.defaultdict(collections.Counter)
    errors = collections.Counter()
    spend = collections.Counter()
    for jid, r in replies.items():
        j = jobs[jid]
        pin, pout = PRICES[j["provider"]]
        spend[j["provider"]] += (r["usage"]["input"] * pin + r["usage"]["output"] * pout) / 1e6
        key = (j["probe"], j["arm"], j["provider"], (j["harness"], j["variant"]))
        if r["error"]:
            errors[key] += 1
            table[key]["error"] += 1
            continue
        conv = PROBES[j["probe"]]["arms"][j["arm"]]
        table[key][outcome(PROBES[j["probe"]]["score"], conv.get("expect"), r["reply"])] += 1
    lines = ["# Phase 1: voice probes through harnesses\n",
             "Counts per arm. Generated by `bench/phase1.py`; every reply is in `replies.md`. "
             "Scores are a first automatic pass (see `bench/scoring.py`); hand checks are noted in "
             "FINDINGS.md.\n",
             f"Spend: Claude ${spend['anthropic']:.4f}, OpenAI ${spend['openai']:.4f} "
             f"(from returned token usage).\n"]
    for pname, probe in PROBES.items():
        keys = [k for k in table if k[0] == pname]
        if not keys:
            continue
        lines.append(f"## {pname}\n\n{probe['about']}\n")
        harn = sorted({k[3] for k in keys}, key=lambda h: list(LABEL).index(h))
        for provider in [p for p in ("anthropic", "openai", "ollama") if any(k[2] == p for k in keys)]:
            lines.append(f"**{MODEL[provider]}**\n")
            lines.append("| arm | " + " | ".join(LABEL[h] for h in harn) + " |")
            lines.append("|---|" + "---|" * len(harn))
            for arm in probe["arms"]:
                cells = []
                for h in harn:
                    c = table.get((pname, arm, provider, h))
                    cells.append(", ".join(f"{k} {v}" for k, v in c.most_common()) if c else "")
                lines.append(f"| {arm} | " + " | ".join(cells) + " |")
            lines.append("")
    (out / "summary.md").write_text("\n".join(lines))
    # every reply, grouped, for reading
    rl = ["# Phase 1 replies\n"]
    for jid in sorted(replies):
        r, j = replies[jid], jobs[jid]
        conv = PROBES[j["probe"]]["arms"][j["arm"]]
        sc = "error" if r["error"] else outcome(PROBES[j["probe"]]["score"], conv.get("expect"), r["reply"])
        txt = (r["reply"] or r["error"] or "").replace("\n", " ⏎ ")
        rl.append(f"- `{jid}` **{sc}**: {txt[:600]}")
    (out / "replies.md").write_text("\n".join(rl))
    print("\n".join(lines))
    if errors:
        print("errors:", dict(errors))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=10)
    ap.add_argument("--out", default=str(ROOT / "results/phase1"))
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--providers", nargs="*", default=["anthropic", "openai"],
                    help="anthropic, openai, ollama (OLLAMA_BASE_URL, OLLAMA_MODEL; default qwen3:8b)")
    ap.add_argument("--concurrency", type=int, default=4)
    ap.add_argument("--cap", type=float, default=2.0, help="refuse to start above this estimate ($)")
    ap.add_argument("--score-only", action="store_true")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    if not a.score_only:
        jobs = build_jobs(a.runs, a.only, a.providers)
        est = estimate(jobs)
        print(f"{len(jobs)} jobs; estimate Claude ${est['anthropic']:.3f}, OpenAI ${est['openai']:.3f}")
        if sum(est.values()) > a.cap:
            sys.exit(f"estimate above cap ${a.cap}")
        with open(out / "jobs.jsonl", "w") as f:
            for j in jobs:
                f.write(json.dumps(j, ensure_ascii=False) + "\n")
        run(out, out / "jobs.jsonl", a.concurrency)
    score(out)
