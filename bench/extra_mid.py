"""Follow-up to Phase 1 `mid-change` on Claude: why did Pydantic AI's framed instruction work
(20/20 German) where the native mid-conversation system role mostly didn't (9/20)?

Four arms, hand-rolled on the raw Messages API, same bakery conversation, 20 runs each:
    native            role "system" after the user's question (Phase 1 hand-rolled)
    native+rule       the same, plus one line in the top prompt: later application instructions
                      replace earlier ones
    framed            "<system verified>From now on, reply in German.</system>" as text after the
                      user's question, in the same user turn, no preamble
    framed+preamble   the same, with Pydantic AI 2.68's preamble added to the top prompt
                      (copied from the recorded request, results/phase0/wire/pydantic-anthropic)

    python bench/extra_mid.py --runs 20
"""

import argparse
import asyncio
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "bench"))
from probes import BAKERY  # noqa: E402
from run_py import CLAUDE, key  # noqa: E402
from scoring import language  # noqa: E402

PREAMBLE = json.loads((ROOT / "results/phase0/wire/pydantic-anthropic/04.json").read_text())["body"]["system"][0]["text"]
RULE = "Later instructions from the application replace earlier ones."
CHANGE = "From now on, reply in German."
HIST = [{"role": "user", "content": "Hi! Are you open on Sundays?"},
        {"role": "assistant", "content": "Bonjour ! Non, nous sommes fermés le dimanche. "
                                         "Nous sommes ouverts du lundi au samedi, de 8 h à 18 h."}]
Q = "What are your opening hours?"


def arm(name):
    if name == "native":
        return BAKERY, HIST + [{"role": "user", "content": Q}, {"role": "system", "content": CHANGE}]
    if name == "native+rule":
        return BAKERY + "\n\n" + RULE, HIST + [{"role": "user", "content": Q}, {"role": "system", "content": CHANGE}]
    framed = [{"role": "user", "content": [{"type": "text", "text": Q},
                                           {"type": "text", "text": f"<system verified>{CHANGE}</system>"}]}]
    if name == "framed":
        return BAKERY, HIST + framed
    if name == "framed+preamble":
        return PREAMBLE + "\n\n" + BAKERY, HIST + framed
    raise ValueError(name)


def classify(t):
    import re
    lang = language(t)
    resisted = bool(re.search(r"Französisch|French|français", t))
    if lang == "de" and not resisted:
        return "clean German"
    if lang == "fr" or (lang == "mixed" and resisted):
        return "kept French"
    return "other"


async def main(runs, out):
    import anthropic
    client = anthropic.AsyncAnthropic(api_key=key("anthropic"), max_retries=4)
    sem = asyncio.Semaphore(4)
    usage = [0, 0]
    rows = []

    async def one(name, i):
        system, msgs = arm(name)
        async with sem:
            r = await client.messages.create(model=CLAUDE, max_tokens=1000, system=system, messages=msgs,
                                             output_config={"effort": "low"})
        usage[0] += r.usage.input_tokens
        usage[1] += r.usage.output_tokens
        t = "".join(b.text for b in r.content if b.type == "text")
        rows.append({"arm": name, "run": i, "reply": t, "class": classify(t)})
    arms = ["native", "native+rule", "framed", "framed+preamble"]
    await asyncio.gather(*(one(a, i) for a in arms for i in range(runs)))
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "replies.jsonl", "w") as f:
        for r in sorted(rows, key=lambda r: (r["arm"], r["run"])):
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    c = collections.defaultdict(collections.Counter)
    for r in rows:
        c[r["arm"]][r["class"]] += 1
    lines = ["# Follow-up: why Pydantic AI's framed mid-conversation instruction worked on Claude\n",
             f"Claude Haiku 5.5, effort low, {runs} runs per arm, hand-rolled raw API. Cost "
             f"${(usage[0] * 0.10 + usage[1] * 0.50) / 1e6:.4f}. Generated by `bench/extra_mid.py`.\n",
             "| arm | clean German | kept French | other |", "|---|---|---|---|"]
    for a in arms:
        lines.append(f"| {a} | {c[a]['clean German']} | {c[a]['kept French']} | {c[a]['other']} |")
    (out / "summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=20)
    a = ap.parse_args()
    asyncio.run(main(a.runs, ROOT / "results/phase1-followup"))
